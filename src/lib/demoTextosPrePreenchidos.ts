/** Mapa completo para persistir na sessão (todas as chaves padrão). */
export function buildDemoTextosCompletos(extraTipos: string[] = []): Record<string, string> {
  const tipos = [...new Set([...tiposPadraoGerarTextosDemo(), ...extraTipos.filter((t) => !isTipoExcluidoGerarTextos(t))])];
  const out: Record<string, string> = {};
  for (const tipo of tipos) {
    out[tipo] = getDemoTextoParaTipo(tipo);
  }
  for (const [k, v] of Object.entries(DEMO_TEXTOS_PREENCHIDOS)) {
    if (!out[k]) out[k] = v;
  }
  return out;
}
