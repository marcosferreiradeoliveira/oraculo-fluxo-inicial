export function normalizeTipoKey(tipo: string): string {
  return tipo
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '');
}

/** Planilha/cronograma têm etapas dedicadas no wizard demo. */
export function isTipoExcluidoGerarTextos(tipo: string): boolean {
  const key = normalizeTipoKey(tipo);
  return (
    key.includes('orcament') ||
    key.includes('planilha') ||
    key === 'orcamento' ||
    key.includes('cronogram')
  );
}

export function filtrarTiposGerarTextos(tipos: string[]): string[] {
  const filtrados = tipos.filter((t) => !isTipoExcluidoGerarTextos(t));
  return filtrados.length > 0 ? filtrados : tiposPadraoGerarTextosDemo();
}

/** Resolve texto demo para qualquer rótulo do edital (snake_case ou frase). */
export function getDemoTextoParaTipo(tipo: string): string {
  if (!tipo?.trim()) return '';

  const raw = tipo.trim();
  if (DEMO_TEXTOS_PREENCHIDOS[raw]) return DEMO_TEXTOS_PREENCHIDOS[raw];

  const key = normalizeTipoKey(raw);
  if (DEMO_TEXTOS_PREENCHIDOS[key]) return DEMO_TEXTOS_PREENCHIDOS[key];

  if (key.includes('acessibil')) return TEXTO_ACESSIBILIDADE;
  if (key.includes('distribu') || key.includes('circulac')) return TEXTO_PLANO_DISTRIBUICAO;
  if (key.includes('descritiv') || (key.includes('projeto') && !key.includes('orcament'))) {
    return TEXTO_DESCRITIVO;
  }
  if (key.includes('portf') || key.includes('portfolio') || key.includes('realizac')) {
    return TEXTO_PORTFOLIO;
  }
  if (key.includes('justific')) return TEXTO_JUSTIFICATIVA;
  if (key.includes('objetiv')) return TEXTO_OBJETIVOS;
  if (key.includes('metodolog')) return TEXTO_METODOLOGIA;
  if (key.includes('resultado')) return TEXTO_RESULTADOS;
  if (key.includes('resumo')) return TEXTO_RESUMO;
  if (key.includes('publico')) return TEXTO_PUBLICO;
  if (key.includes('comunic') || key.includes('divulg')) return TEXTO_COMUNICACAO;
  if (key.includes('impacto')) return TEXTO_RESULTADOS;
  if (key.includes('orcament') || key.includes('planilha')) return DEMO_TEXTOS_PREENCHIDOS.planilha_orcamentaria;
  if (key.includes('cronogram')) return DEMO_TEXTOS_PREENCHIDOS.cronograma;

  return TEXTO_DESCRITIVO;
}

export function tituloTipoTexto(tipo: string): string {
  const t = tipo.trim();
  if (/[\s\u00C0-\u024F]/.test(t) && !t.includes('_')) {
    return t.charAt(0).toUpperCase() + t.slice(1);
  }
  return t
    .split('_')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join(' ');
}

